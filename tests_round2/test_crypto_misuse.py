"""Group 7: Cryptographic Misuse and Robustness Tests."""
from __future__ import annotations

import base64
import json
from pathlib import Path
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from quantumvault.core.errors import CryptoError
from quantumvault.crypto.encryption import AuthenticatedEncryption
from quantumvault.crypto.pqc_dsa import MLDSA65
from quantumvault.crypto.pqc_kem import MLKEM768


class TestCryptoMisuse(unittest.TestCase):
    def test_crypto01_nonce_uniqueness_over_10000_encryptions(self):
        """Check 10,000 AES-256-GCM nonces generated by AuthenticatedEncryption have zero collisions."""
        cipher = AuthenticatedEncryption(b"K" * 32)
        nonces = set()
        count = 10000
        for _ in range(count):
            ciphertext, nonce = cipher.encrypt_bytes(b"Benchmark payload data")
            self.assertNotIn(nonce, nonces, "CRITICAL: Nonce collision detected in AES-256-GCM!")
            nonces.add(nonce)
        self.assertEqual(len(nonces), count)

    def test_crypto02_kem_ciphertext_tampering_and_wrong_key(self):
        """ML-KEM-768 ciphertext tampering and wrong-key decapsulation fail safely."""
        kem = MLKEM768()
        pk1, sk1 = kem.generate_keypair()
        pk2, sk2 = kem.generate_keypair()

        ct, ss1 = kem.encapsulate(pk1)

        # 1. Tamper with 1 byte of ciphertext
        ct_tampered = bytearray(ct)
        ct_tampered[0] ^= 0xFF
        # Under NIST FIPS 203 Kyber implicit rejection, decapsulation on tampered ciphertext returns
        # a pseudorandom secret that differs from the sender's shared secret
        ss_tampered = kem.decapsulate(sk1, bytes(ct_tampered))
        self.assertNotEqual(ss1, ss_tampered, "CRITICAL: Tampered KEM ciphertext produced matching shared secret!")

        # 2. Wrong key decapsulation
        ss_wrong = kem.decapsulate(sk2, ct)
        self.assertNotEqual(ss1, ss_wrong, "CRITICAL: Wrong private key produced matching shared secret!")

    def test_crypto03_signature_context_binding(self):
        """ML-DSA-65 signature on Action A does not verify for Action B."""
        dsa = MLDSA65()
        pk, sk = dsa.generate_keypair()

        msg_allow = b'{"action": "allow_access", "resource": "financial_vault"}'
        msg_deny = b'{"action": "deny_access", "resource": "financial_vault"}'

        sig = dsa.sign(sk, msg_allow)
        self.assertTrue(dsa.verify(pk, msg_allow, sig))
        self.assertFalse(dsa.verify(pk, msg_deny, sig), "CRITICAL: Signature verified for unauthorized action!")

    def test_crypto04_canonical_json_serialization(self):
        """Check whether JSON signing uses canonical key ordering and whitespace."""
        dsa = MLDSA65()
        pk, sk = dsa.generate_keypair()

        obj_a = {"alpha": 1, "beta": 2}
        obj_b = {"beta": 2, "alpha": 1}

        # Canonical dump (sort_keys=True, separators=(',', ':'))
        canon_a = json.dumps(obj_a, sort_keys=True, separators=(",", ":")).encode("utf-8")
        canon_b = json.dumps(obj_b, sort_keys=True, separators=(",", ":")).encode("utf-8")
        self.assertEqual(canon_a, canon_b)

        sig_a = dsa.sign(sk, canon_a)
        self.assertTrue(dsa.verify(pk, canon_b, sig_a))

        # Non-canonical dump (different whitespace) must fail
        non_canon = b'{"alpha": 1,  "beta": 2}'
        self.assertFalse(dsa.verify(pk, non_canon, sig_a))

    def test_crypto05_algorithm_downgrade_rejection(self):
        """Ensure invalid or malformed public key sizes in ML-KEM-768 are rejected."""
        kem = MLKEM768()
        # Classical 32-byte X25519 public key injected into ML-KEM-768
        x25519_fake_key = b"X" * 32
        with self.assertRaises(CryptoError) as cm:
            kem.encapsulate(x25519_fake_key)
        self.assertIn("length", str(cm.exception).lower())


if __name__ == "__main__":
    unittest.main()
